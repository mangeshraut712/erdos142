"""Run: python3 verify_coset_lemmas_20261002.py. Exact checks of the
elementary facts used in MIXED_FACTORS_20261002.md sections 7-9:

1. Product minorant (pointwise): if 0 <= a_j, b_j^- <= a_j <= b_j^+, then
   prod a_j >= sum_j b_j^- prod_{l!=j} b_l^+ - (k-1) prod_l b_l^+.
2. Averaging over a coset of (1/q)Z: (1/q) sum_l g(alpha+l/q)
   = sum_{q | t} ghat(t) e(t alpha) for trigonometric polynomials g.
3. Covolume under absorption in Z^k: adding m outside the rational span
   multiplies covol by at most |m|_2; adding m in span but not in the
   lattice divides covol by an integer >= 2. Covolume = sqrt(det Gram).
"""
from fractions import Fraction
import cmath
import json
import math
import random


def check_minorant(rng, trials=20000):
    worst = math.inf
    for _ in range(trials):
        k = rng.randrange(1, 7)
        a = [rng.random() for _ in range(k)]
        lo = [x - rng.random()*rng.choice((0, 0.3, 2)) for x in a]
        hi = [x + rng.random()*rng.choice((0, 0.3, 2)) for x in a]
        prod_hi = math.prod(hi)
        rhs = sum(lo[j]*math.prod(hi[:j] + hi[j + 1:]) for j in range(k)) - (k - 1)*prod_hi
        gap = math.prod(a) - rhs
        assert gap >= -1e-9
        worst = min(worst, gap)
    return worst


def check_averaging(rng, trials=300):
    worst = 0.0
    for _ in range(trials):
        H = rng.randrange(1, 12)
        coef = {t: complex(rng.gauss(0, 1), rng.gauss(0, 1)) for t in range(-H, H + 1)}
        q = rng.randrange(1, 15)
        alpha = rng.random()
        g = lambda x: sum(c*cmath.exp(2j*math.pi*t*x) for t, c in coef.items())
        lhs = sum(g(alpha + l/q) for l in range(q))/q
        rhs = sum(c*cmath.exp(2j*math.pi*t*alpha) for t, c in coef.items() if t % q == 0)
        worst = max(worst, abs(lhs - rhs))
        assert abs(lhs - rhs) < 1e-9
    return worst


def det(mat):
    m = [[Fraction(x) for x in row] for row in mat]
    n, d = len(m), Fraction(1)
    for i in range(n):
        piv = next((r for r in range(i, n) if m[r][i] != 0), None)
        if piv is None:
            return Fraction(0)
        if piv != i:
            m[i], m[piv] = m[piv], m[i]
            d = -d
        d *= m[i][i]
        for r in range(i + 1, n):
            f = m[r][i]/m[i][i]
            m[r] = [x - f*y for x, y in zip(m[r], m[i])]
    return d


def gram_det(vecs):
    return det([[sum(x*y for x, y in zip(u, v)) for v in vecs] for u in vecs])


def basis_of(vecs):
    """Z-basis of the lattice generated by integer vectors (Hermite reduction)."""
    rows = [list(v) for v in vecs if any(v)]
    k = len(vecs[0])
    basis, col = [], 0
    while rows and col < k:
        nz = [r for r in rows if r[col] != 0]
        if not nz:
            col += 1
            continue
        while len(nz) > 1:
            nz.sort(key=lambda r: abs(r[col]))
            p = nz[0]
            new = [p]
            for r in nz[1:]:
                f = r[col]//p[col]
                rr = [x - f*y for x, y in zip(r, p)]
                if rr[col] != 0:
                    new.append(rr)
                elif any(rr):
                    rows.append(rr)
            nz = new
        p = nz[0]
        basis.append(p)
        rows = [r for r in rows if r[col] == 0 and r is not p and any(r)]
        col += 1
    return basis


def check_covolume(rng, trials=3000):
    rank_steps = index_steps = 0
    for _ in range(trials):
        k = rng.randrange(2, 5)
        gens = [[rng.randrange(-4, 5) for _ in range(k)] for _ in range(rng.randrange(1, k))]
        base = basis_of(gens)
        if not base:
            continue
        g0 = gram_det(base)
        if g0 == 0:
            continue
        m = [rng.randrange(-6, 7) for _ in range(k)]
        if rng.random() < 0.5:
            coeffs = [Fraction(rng.randrange(-3, 4), rng.randrange(1, 4)) for _ in base]
            mm = [sum(c*b[i] for c, b in zip(coeffs, base)) for i in range(k)]
            if all(x.denominator == 1 for x in mm):
                m = [int(x) for x in mm]
        new = basis_of(base + [m])
        g1 = gram_det(new)
        if len(new) == len(base) + 1:
            assert g1 <= g0*sum(x*x for x in m)
            rank_steps += 1
        elif g1 != g0:
            ratio = g0/g1
            assert ratio.denominator == 1 and ratio >= 4
            assert math.isqrt(ratio.numerator)**2 == ratio.numerator
            index_steps += 1
    return rank_steps, index_steps


def main():
    rng = random.Random(9)
    m = check_minorant(rng)
    a = check_averaging(rng)
    rs, ix = check_covolume(rng)
    print("minorant min gap", m, "averaging max err", a, "rank steps", rs, "index steps", ix)
    assert rs > 50 and ix > 20
    with open(Path(__file__).resolve().parents[1] / "results" / "coset_lemmas_verification_20261002.json", "w") as fh:
        json.dump({"minorant_min_gap": m, "averaging_max_error": a,
                   "covolume_rank_steps": rs, "covolume_index_steps": ix,
                   "target_proved": False}, fh, indent=1)


if __name__ == "__main__":
    main()
